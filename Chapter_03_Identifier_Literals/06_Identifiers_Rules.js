// 1. An identifier can start with a letter.
var name = "Kalpa";

// 2. An identifier can start with $.
var $price = 100;

// 3. An identifier can start with _.
var _count = 12;

// 4. Numbers are allowed after the first character.
var student1 = "Alex";
var item2026 = "Laptop";

// 5. Identifiers are case-sensitive.
var age = 20;
var Age = 25;

// 6. Identifiers can contain letters, numbers, $ and _.
var first_name = "Alex";
var account$number_1 = 12345;

// 7. Unicode letters can be used in identifiers.
var café = "Coffee";

